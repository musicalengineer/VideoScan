    private static func render(_ resolution: GedcomFamilyGraph.KinshipResolution,
                               from subject: GedcomFamilyGraph.Person) -> String {
        switch resolution {
        case .found(let paths):
            return "found: " + paths.map { $0.describe(from: subject) }.joined(separator: " | ")
        case .missingHop(let reached, let missing):
            return "missing: " + reached.map { "\($0.label) \($0.person.name)" }.joined(separator: " | ") + " ⟂ " + missing
        }
    }

