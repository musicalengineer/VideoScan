        XCTAssertEqual(Self.golden.count, 5 * Relation.allCases.count * 3)
        for (subjectID, relation, side, expected) in Self.golden {
            let subject = Self.graph.people[subjectID]!
            XCTAssertEqual(Self.render(Self.graph.relatives(relation, side: side, of: subject), from: subject),
                           expected, "\(subjectID) \(relation) \(side?.rawValue ?? "no side")")
        }
    }

